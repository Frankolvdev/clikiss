test('capacity protects resources without charging P2P calls for fictional relay traffic',()=>{
 const config=callConfig({VIDEO_CALL_MAX_ACTIVE:'20'});
 const metrics={cpu:0.1,freeMb:4096,networkMbps:0};
 assert.equal(capacityDecision(config,metrics,19).available,true);
 assert.equal(capacityDecision(config,metrics,20).available,false);
 assert.equal(capacityDecision(config,{...metrics,cpu:0.99},0).available,false);
 assert.equal(capacityDecision(config,{...metrics,freeMb:10},0).available,false);
 assert.equal(capacityDecision({...config,networkMbps:100},{...metrics,networkMbps:90},0).available,false);
 assert.equal(capacityDecision({...config,enabled:false},metrics,0).reason,'disabled');
 assert.equal(capacityDecision({...config,requireTurn:true},metrics,0).available,false);
});
test('temporary TURN credentials are call-bound, signed and bounded',()=>{
 const config=callConfig({TURN_SHARED_SECRET:'a'.repeat(64),TURN_URLS:'turn:relay.example.test:3478?transport=udp'});
 const created=new Date();const call={id:randomUUID(),created_at:created};
 const rtc=iceConfiguration(config,call,'person');
 const turn=rtc.iceServers.find(s=>s.username);
 assert.equal(turn.credential,createHmac('sha1',config.secret).update(turn.username).digest('base64'));
 assert(Number(turn.username.split(':')[0])>Date.now()/1000);
 assert(!JSON.stringify(rtc).includes(config.secret));
});
test('PostgreSQL call lifecycle, isolation, concurrency, timeout and cleanup',async()=>{
 if(!process.env.DATABASE_URL||!['localhost','127.0.0.1'].includes(new URL(process.env.DATABASE_URL).hostname))throw Error('Use the local test database only.');
 const root=new Pool({connectionString:process.env.DATABASE_URL,max:1});
 const schema='call_test_'+randomUUID().replaceAll('-','');
 await root.query(`CREATE SCHEMA ${schema}`);
 const db=new Pool({connectionString:process.env.DATABASE_URL,options:`-c search_path=${schema},public`,max:2});
 try{
  await db.query('CREATE TABLE "user"(id text PRIMARY KEY,name text,"emailVerified" boolean DEFAULT true,"emailVerificationRequired" boolean DEFAULT true); CREATE TABLE profiles(user_id text,suspended_at timestamptz); CREATE TABLE conversations(id uuid PRIMARY KEY,user_low text,user_high text); CREATE TABLE user_blocks(user_id text,target_id text)');
  await db.query('CREATE TABLE application_settings(id boolean PRIMARY KEY,require_email_verification boolean); INSERT INTO application_settings VALUES(true,true)');
  await db.query(await readFile(new URL('../db/migrations/014_video_calls.sql',import.meta.url),'utf8'));
  const ids=Array.from({length:12},(_,i)=>`user-${i}`),clients=ids.map(()=>randomUUID());
  for(const id of ids)await db.query('INSERT INTO "user"(id,name) VALUES($1,$1)',[id]);
  for(let i=0;i<ids.length;i+=2)await db.query('INSERT INTO conversations VALUES($1,LEAST($2::text,$3::text),GREATEST($2::text,$3::text))',[randomUUID(),ids[i],ids[i+1]]);
  const config=callConfig({VIDEO_CALL_MAX_ACTIVE:'2'});let metrics={cpu:0,freeMb:4096,networkMbps:0};
  const service=createCallService(db,{config,measure:async()=>metrics});
  const start=(i)=>service.act(ids[i],{action:'start',clientId:clients[i],targetId:ids[i+1]});
  await assert.rejects(service.act(ids[0],{action:'start',clientId:clients[0],targetId:ids[3]}),e=>e.status===403);
  const results=await Promise.allSettled([start(0),start(0)]);
  assert.equal(results.filter(r=>r.status==='fulfilled').length,1);
  const first=results.find(r=>r.status==='fulfilled').value.id;
  const second=(await start(2)).id;
  await assert.rejects(start(4),e=>e.status===503);
  await assert.rejects(service.state(ids[4],clients[4],first),e=>e.status===404);
  await assert.rejects(service.act(ids[4],{action:'accept',callId:first,clientId:clients[4]}),e=>e.status===404);
  const incoming=await service.state(ids[1],clients[1]);assert(incoming.call.incoming);
  await service.act(ids[1],{action:'accept',callId:first,clientId:clients[1]});
  await assert.rejects(service.act(ids[1],{action:'accept',callId:first,clientId:randomUUID()}),e=>e.status===409);
  await assert.rejects(service.act(ids[0],{action:'signal',callId:first,clientId:randomUUID(),id:randomUUID(),signals:[{type:'offer',sdp:'v=0'}]}),e=>e.status===409);
  const signal={action:'signal',callId:first,clientId:clients[0],id:randomUUID(),signals:[{type:'offer',sdp:'v=0'}]};
  await service.act(ids[0],signal);await service.act(ids[0],signal);
  const received=await service.state(ids[1],clients[1],first);assert.equal(received.signals.length,1);
  assert.equal((await service.state(ids[1],clients[1],first,Number(received.signals[0].seq))).signals.length,0);
  await service.act(ids[0],{action:'heartbeat',callId:first,clientId:clients[0],connected:true,route:'direct'});
  assert.equal((await service.state(ids[0],clients[0],first)).call.status,'active');
  await db.query('INSERT INTO user_blocks VALUES($1,$2)',[ids[0],ids[1]]);
  await cleanupCalls(db,config);
  assert.equal((await service.state(ids[0],clients[0],first)).call.endReason,'blocked');
  assert.equal((await db.query('SELECT count(*)::int AS n FROM video_call_signals WHERE call_id=$1',[first])).rows[0].n,0);
  await service.act(ids[3],{action:'end',callId:second,clientId:clients[3]});
  assert.equal((await service.state(ids[2],clients[2],second)).call.endReason,'rejected');
  metrics={...metrics,cpu:0.99};await assert.rejects(start(4),e=>e.status===503);
  metrics={...metrics,cpu:0};const timed=(await start(4)).id;
  await db.query("UPDATE video_calls SET created_at=now()-interval '50 seconds' WHERE id=$1",[timed]);await cleanupCalls(db,config);
  assert.equal((await service.state(ids[4],clients[4],timed)).call.endReason,'missed');
  const abandoned=(await start(4)).id;await service.act(ids[5],{action:'accept',callId:abandoned,clientId:clients[5]});
  await db.query("UPDATE video_calls SET callee_seen=now()-interval '80 seconds' WHERE id=$1",[abandoned]);await cleanupCalls(db,config);
  assert.equal((await service.state(ids[4],clients[4],abandoned)).call.endReason,'connection-lost');
  await db.query('UPDATE "user" SET "emailVerified"=false WHERE id=ANY($1::text[])',[[ids[4],ids[5]]]);
  await assert.rejects(start(4),error=>error.status===403);
  await db.query('UPDATE application_settings SET require_email_verification=false');
  await assert.rejects(start(4),error=>error.status===403);
  await db.query('UPDATE "user" SET "emailVerificationRequired"=false WHERE id=ANY($1::text[])',[[ids[4],ids[5]]]);
  const unverified=(await start(4)).id;
  await service.act(ids[5],{action:'accept',callId:unverified,clientId:clients[5]});
  await db.query('UPDATE application_settings SET require_email_verification=true');await cleanupCalls(db,config);
  assert.equal((await service.state(ids[4],clients[4],unverified)).call.status,'connecting');
  await db.query('UPDATE "user" SET "emailVerificationRequired"=true WHERE id=ANY($1::text[])',[[ids[4],ids[5]]]);await cleanupCalls(db,config);
  assert.equal((await service.state(ids[4],clients[4],unverified)).call.status,'ended');
  await db.query('UPDATE "user" SET "emailVerified"=true WHERE id=ANY($1::text[])',[[ids[4],ids[5]]]);
  // More callers than capacity arriving simultaneously must never overbook.
  const burst=await Promise.allSettled([start(4),start(6),start(8),start(10)]);
  assert.equal(burst.filter(r=>r.status==='fulfilled').length,2);
  assert.equal((await db.query('SELECT count(*)::int AS n FROM video_call_slots')).rows[0].n,4);
 }finally{await db.end();await root.query(`DROP SCHEMA ${schema} CASCADE`);await root.end();}
});
